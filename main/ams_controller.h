/**
 * 便捷封装：485 运动指令直接驱动电机（**非阻塞**）。
 *
 * ★ 2026-10-23 现场定位：485（BMCU）通信下，进料/退料是打印机通过
 *   Cxx（cmd=0x03）运动帧下发的 —— 收到「进料」就正转、收到「退料」就
 *   反转、收到「到位」就停。这跟 MQTT 换料（do_load/do_retract 的 20 秒
 *   闭环 + hw_switch_state 判据）是**两套互斥的机制**。
 *
 * 本接口用非阻塞的 motor_set_dir_speed()：离合吸合 + 电机持续转，立即返回。
 * 停止由后续的 ams_post_stop()（打印机发 0x07 到位 / 0x01 卸载时）触发。
 * 这样电机完全跟随打印机的 485 指令节奏，不会被阻塞式换料卡住。
 *
 * @param material_index 料盘位下标（0 起）
 * @param direction      1 = 进料（正转）；-1 = 退料（反转）
 */
bool ams_post_485_drive(int material_index, int direction);

/**
 * 485 进料「到位立即停」后的双微动决策层入口。
 *
 * ★★ 2026-10-24 用户拍板：到位(0x07/0x00 stop_on_use)立即停电机后，
 *   靠该通道两只微动（常开 4.7k 开始位 + 常闭 10k 停止位，ADC 三态）
 *   决定「续送 / 断料」：停止微动触发 = 料已咬稳 → 保持断料；
 *   开始微动触发 = 余料要补 → 短促续送一段再复查停止微动；
 *   6s 无微动响应 → 超时断离合回 idle。
 *
 * 由 comm_485.c 在状态机转入 MOT_STOP_ON_USE 时调用。决策本身在 ams_task
 * 主循环里轮询（poll_485_decide），这里只负责"开窗"。
 *
 * @param ch 料盘位下标（0 起）
 */
void ams_485_enter_decide_window(int ch);

/**
 * 关闭 485 到位决策窗口（0.30.1）。
 *
 * 状态机**离开** MOT_STOP_ON_USE 时必须调用：打印机在到位后约 0.9 秒就发
 * before_pull_back 退料，而决策窗口有 6 秒，不关窗的话退料期间 poll_485_decide
 * 还会正转续送，与退料指令方向相反地互搏（"到位后反复进退料"）。
 *
 * 由 comm_485.c 的 mot_set() 在通道离开 MOT_STOP_ON_USE 时调用。
 */
void ams_485_exit_decide_window(void);

/**
 * 标记决策窗口为「到位后窗口」（0.31.0）。
 *
 * on_use / before_on_use 期间的随动窗口不设 6s 超时（挤出机可能拉料很久），
 * 只有 stop_on_use 到位后的窗口才检查超时。由 comm_485.c 的 mot_set() 在
 * 转入 MOT_STOP_ON_USE 时调用。
 */
void ams_485_mark_decide_stop(void);

/** 便捷封装：换料到指定打印机通道（1 起） */
bool ams_post_exchange(int printer_channel);

/**
 * 便捷封装：**辅助送料自检** —— 立刻按网页上的「辅助送料」配置
 * （占空比 / 时长）驱动一次当前通道的电机，并用完整回执把硬件回读打出来。
 *
 * ★ 为什么要有这个按钮（2026-09-23 现场反馈）：
 *   用户报"辅助送料没作用，电磁吸合了但电机不转"。而辅助送料是**由打印机
 *   阶段驱动**的 —— 要验证它，正常得等下一轮打印、等到校准阶段，一次十几
 *   分钟，还不一定复现。这个自检把"验证一次辅助送料"变成点一下按钮：
 *     · 手动点动（duty 255）转、辅助送料（自检，duty 随网页设置）不转
 *       → 就是占空比不够，把网页上的速度往上调；
 *     · 两个都不转 → 硬件链路（H 桥使能、离合齿轮、接线），不是软件。
 *
 * @param material_index 料盘位下标（0 起）；-1 = 用当前记录的通道
 */
bool ams_post_assist_test(int material_index);

/**
 * 辅助送料「阶段内保持离合吸合」当前保持在哪一路。
 *
 * @return 料盘位 1~4（= 网页上的通道号）；0 = 当前没有保持
 *
 * ★ 为什么要有这个查询（2026-09-23 现场要求）：
 *   开了「保持吸合」之后，离合在整段校准 / 打印期间一直是吸着的，而这时
 *   状态机显示的是"空闲"（保持的是机械状态，不是总线占用，见 ams_controller.c
 *   里那段说明）。用户光看状态看不出"离合现在到底吸着没有"，所以单独暴露
 *   一个字段给网页显示，配合 clutch 自己的 engaged 掩码一起看。
 */
int ams_assist_hold_channel(void);

